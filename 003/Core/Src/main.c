// 串口接收中断回调函数
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART2) { /* 切换为 USART2 */
        // 收到帧头 0xAA 启动解析
        if (rx_byte == 0xAA) {
            rx_idx = 0;
            rx_buf[rx_idx++] = rx_byte;
        } else if (rx_idx > 0) {
            rx_buf[rx_idx++] = rx_byte;
            // 收到 3 字节完整请求帧 (0xAA 0x01 0x55)
            if (rx_idx == 3 && rx_buf[2] == 0x55) {
                // 读取 RTC 时间并打包回传
                RTC_TimeTypeDef sTime = {0};
                RTC_DateTypeDef sDate = {0};
                HAL_RTC_GetTime(&hrtc, &sTime, RTC_FORMAT_BIN);
                HAL_RTC_GetDate(&hrtc, &sDate, RTC_FORMAT_BIN);

                uint8_t tx_buf[7] = {0xAA, sTime.Hours, sTime.Minutes, sTime.Seconds, 0x00, 0x00, 0x55};
                HAL_UART_Transmit(&huart2, tx_buf, 7, 100);

                rx_idx = 0; // 重置索引
            }
        }
        // 重新开启 USART2 接收中断
        HAL_UART_Receive_IT(&huart2, &rx_byte, 1);
    }
}

/* 3. 更新 USART2 错误防卡死回调 */
void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART2) {
        __HAL_UART_CLEAR_OREFLAG(huart);
        __HAL_UART_CLEAR_NEFLAG(huart);
        __HAL_UART_CLEAR_FEFLAG(huart);

        HAL_UART_Receive_IT(&huart2, &rx_byte, 1);
    }
}
